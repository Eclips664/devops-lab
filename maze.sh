#!/bin/bash
# Нажмите Ctrl+C для выхода

# Возвращаем стандартные цвета терминала при выходе
trap 'echo -e "\e[0m"; clear; exit' INT TERM

while true; do
    # Выбираем случайный цвет от 31 до 36 (красный, зеленый, желтый, синий, пурпурный, циан)
    color=$((31 + RANDOM % 6))
    
    # Случайно выбираем символ / или \
    [ $((RANDOM % 2)) -eq 0 ] && char="/" || char="\\"
    
    # Выводим цветной символ без переноса строки
    echo -ne "\e[${color}m${char}"
done


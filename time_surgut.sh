#!/bin/bash

# Скрываем курсор для красоты (вернем при выходе)
trap 'tput cnorm; echo ""; exit' INT TERM

echo "Точное время в Сургуте (для выхода нажмите Ctrl+C):"

while true; do
    # Устанавливаем таймзону Сургута и форматируем вывод (Часы:Минуты:Секунды.Миллисекунды)
    # %N выводит наносекунды, поэтому мы берем первые 3 цифры с помощью куттера
    TZ="Asia/Yekaterinburg" date +"%H:%M:%S.%3N" | tr -d '\n'
    
    # Возвращаем каретку в начало строки (эффект обновления на одном месте)
    echo -ne "\r"
    
    # Небольшая пауза в 0.05 секунды, чтобы не перегружать процессор
    sleep 0.05
done


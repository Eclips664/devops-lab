#!/bin/bash
# Нажимайте Ctrl+C для выхода

# Очищаем экран
clear
# Скрываем курсор для красоты
tput civvis
# Возвращаем курсор обратно, если нажмем Ctrl+C
trap 'tput cnorm; clear; exit' INT TERM

# Массив из японских иероглифов (катакана), цифр и знаков
symbols=(ｱ ｲ ｳ ｴ ｵ ｶ ｷ ｸ ｹ ｺ ｻ ｼ ｽ ｾ ｿ 1 0 X Z \$ 7 9)

while true; do
    # Случайная колонка (ширина терминала)
    col=$((RANDOM % $(tput cols)))
    # Случайная строка (высота терминала)
    row=$((RANDOM % $(tput lines)))
    # Случайный символ из нашего массива
    char=${symbols[$((RANDOM % ${#symbols[@]}))]}
    
    # Рисуем зеленый символ в случайном месте экрана
    tput cup $row $col
    echo -e "\e[32m$char\e[0m"
    
    # Очень маленькая пауза, чтобы не нагружать процессор
    sleep 0.01
done

